"""
One AXI scenario that runs on the Nexys Video (JTAG-AXI) and in the cocotb simulation with the APS12808L model,
so the model can be checked against the real chips.

    python3 hw_scenario.py tcl  > build/hw_scenario.tcl   # board: vivado -mode batch -source run_hw_scenario.tcl
    python3 hw_scenario.py compare build/hw_result.txt <sim_result.txt>

Result format, one line per read:  R <addr hex> <word0 hex> <word1 hex> ...   (sim byte ee = never written)
"""

import sys


def words(seed, n):
    return [((seed * 0x01000193 + i * 0x9E3779B1) ^ (i << 24)) & 0xFFFFFFFF for i in range(n)]


# (op, address, data-or-length)
SCENARIO = [
    # plain burst roundtrips
    ("W", 0x0000, words(1, 8)),
    ("R", 0x0000, 8),
    # single word reads inside the burst written above (aliasing of burst offset vs. start address)
    ("R", 0x0004, 1),
    ("R", 0x0008, 1),
    ("R", 0x000C, 1),
    ("R", 0x0010, 1),
    ("R", 0x001C, 1),
    # single word writes, then burst read over them
    ("W", 0x0100, [0x11111111]),
    ("W", 0x0104, [0x22222222]),
    ("W", 0x0108, [0x33333333]),
    ("W", 0x010C, [0x44444444]),
    ("R", 0x0100, 4),
    ("R", 0x0104, 1),
    ("R", 0x0108, 1),
    # odd word start and odd word count
    ("W", 0x0200, words(2, 8)),
    ("W", 0x0204, words(3, 3)),
    ("R", 0x0200, 8),
    # long bursts, crossing 1K chip bytes with the current mapping
    ("W", 0x2000, words(4, 256)),
    ("R", 0x2000, 256),
    ("R", 0x2400, 4),
    ("R", 0x2800, 4),
    ("R", 0x2C00, 4),
    ("R", 0x2FF0, 4),
    # repeated read of the same data (refresh collisions / variable latency would show up as shifted data)
] + [("R", 0x2000, 256)] * 8


def to_tcl():
    out = [
        "# generated by hw_scenario.py",
        "set fh [open $result_file w]",
        "set axi [lindex [get_hw_axis] 0]",
        "reset_hw_axi $axi",
    ]
    for n, (op, addr, arg) in enumerate(SCENARIO):
        name = f"t{n}"
        if op == "W":
            data = "".join(f"{w:08x}" for w in reversed(arg))  # beat 0 is the rightmost word
            out.append(
                f"create_hw_axi_txn -force {name} $axi -type write -address {addr:08x} -len {len(arg)} "
                f"-data {data}"
            )
            out.append(f"run_hw_axi [get_hw_axi_txns {name}]")
        else:
            out.append(f"create_hw_axi_txn -force {name} $axi -type read -address {addr:08x} -len {arg}")
            out.append(f"run_hw_axi [get_hw_axi_txns {name}]")
            out.append(f"set d [get_property DATA [get_hw_axi_txns {name}]]")
            out.append(
                f'set w {{}}; for {{set i [expr {{[string length $d] - 8}}]}} {{$i >= 0}} {{incr i -8}} '
                f'{{lappend w [string range $d $i [expr {{$i + 7}}]]}}'
            )
            out.append(f'puts $fh "R {addr:08x} [join $w {{ }}]"')
    out.append("close $fh")
    return "\n".join(out) + "\n"


def parse(path):
    lines = [l.split() for l in open(path) if l.startswith("R ")]
    return [(l[1], l[2:]) for l in lines]


def compare(hw_path, sim_path):
    # a read without data = the transaction hung, nothing after it ran
    hw = [r for r in parse(hw_path) if r[1]]
    sim = [r for r in parse(sim_path) if r[1]]
    mismatches = 0
    if len(hw) != len(sim):
        print(f"different number of completed reads: hw {len(hw)}, sim {len(sim)}")
        mismatches += 1
    for n, ((ha, hw_words), (sa, sim_words)) in enumerate(zip(hw, sim)):
        assert ha == sa
        for i, (h, s) in enumerate(zip(hw_words, sim_words)):
            # sim byte "ee" = never written (model INIT_BYTE), the board then returns random data
            same = all(
                sb in ("xx", "ee") or sb == hb
                for hb, sb in zip([h.lower()[j : j + 2] for j in range(0, 8, 2)],
                                  [s.lower()[j : j + 2] for j in range(0, 8, 2)])
            )
            if not same:
                mismatches += 1
                if mismatches <= 40:
                    print(f"read {n} @{ha} word {i}: hw {h} sim {s}")
    print(f"{mismatches} mismatching words")
    return mismatches


if __name__ == "__main__":
    if sys.argv[1] == "tcl":
        sys.stdout.write(to_tcl())
    elif sys.argv[1] == "compare":
        sys.exit(1 if compare(sys.argv[2], sys.argv[3]) else 0)
